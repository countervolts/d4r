#!/usr/bin/env python3
"""Pack decoder 0's extracted weights (engine/rr/dec0_ref.py --extract) for engine/rr/dec0_m.comp.

usage: dec0_pack.py WEIGHTS.npz OUT.bin OUT.h

The layout rules are enc1_pack.py's: transposed products, every weight's columns in the k order of the product that
consumes its result (C = 32: slot j holds natural channel inter(32)[j]). The expand's 128 columns are four
sub-positions of 32 channels, each permuted the same way, so a key token's expanded half is already in slot order.
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from enc1_ref import inter  # noqa: E402
from enc1_pack import a_tiles, b_tiles, cubic_table, act_table  # noqa: E402

I32, I96 = inter(32), inter(96)
I128 = [32 * (j // 32) + I32[j % 32] for j in range(128)]


def main():
    src, out_bin, out_h = sys.argv[1:4]
    w = dict(np.load(src))
    e = {'we': ('A', w['we'][:, I128]), 'be': ('H', w['be'][I128])}
    for h in range(2):
        e[f'wk{h}'] = ('A', w[f'wk{h}'][:, I32])
        e[f'wv{h}'] = ('B', w[f'wv{h}'][:, I32])
        e[f'wo{h}'] = ('A', w[f'wo{h}'][:, I32])
        e[f'bias{h}'] = ('H', w[f'bias{h}'][np.ix_(inter(64), I96)].T)
    for b in range(4):
        e[f'w1_{b}'] = ('A', w[f'w1_{b}'][:, I32])
        e[f'b1_{b}'] = ('H', w[f'b1_{b}'][I32])
        e[f'w2_{b}'] = ('A', w[f'w2_{b}'][:, I32])
    e['gain0'] = ('H', w['gain0'])
    for k in ('table0', 'gain1', 'table1'):
        e[k] = ('H', w[k][I32])
    e['cubic'] = ('U', cubic_table())
    e['act'] = ('Y', act_table())
    blob, defines = bytearray(), []
    for name, (kind, a) in e.items():
        while len(blob) % 256:
            blob.append(0)
        off = len(blob)
        if kind == 'A':
            blob += a_tiles(a).tobytes()
        elif kind == 'B':
            blob += b_tiles(a).tobytes()
        elif kind == 'Y':
            blob += np.ascontiguousarray(a, np.uint8).tobytes()
        elif kind == 'U':
            blob += np.ascontiguousarray(a, np.uint16).tobytes()
        else:
            blob += np.ascontiguousarray(a, np.float16).tobytes()
        defines.append(f'#define W_{name.upper()} {off}u   // {kind} {a.shape}')
    open(out_bin, 'wb').write(bytes(blob))
    open(out_h, 'w').write('// generated by engine/rr/dec0_pack.py\n' + '\n'.join(defines) + '\n')
    print(f'{len(blob)} bytes, {len(e)} entries')


if __name__ == '__main__':
    main()
