#!/usr/bin/env python3
"""Pack encoder 0's extracted weights (engine/rr/enc0_ref.py --extract) for engine/rr/enc0_m.comp's native part.

usage: enc0_pack.py WEIGHTS.npz OUT.bin OUT.h [BASE]

dec0_pack.py's layout (C = 32) plus the embedding (W1, W2: 32 -> 32 -> 32, columns in slot order), the 2x2 merge
(128 -> 64, columns in arena order) and the 32 -> 16 head. BASE (default 0) is added to every offset in OUT.h: the
shader binds NGX's weight image first (its translated feature prologue reads it) and this blob after it.
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from enc1_ref import inter  # noqa: E402
from enc1_pack import a_tiles, b_tiles, cubic_table, act_table  # noqa: E402

I32, I64, I96 = inter(32), inter(64), inter(96)


def main():
    src, out_bin, out_h = sys.argv[1:4]
    base = int(sys.argv[4]) if len(sys.argv) > 4 else 0
    w = dict(np.load(src))
    e = {'w1': ('A', w['w1'][:, I32]), 'b1': ('H', w['b1'][I32]), 'w2': ('A', w['w2'][:, I32]), 'b2': ('H', w['b2'][I32])}
    for h in range(2):
        e[f'wk{h}'] = ('A', w[f'wk{h}'][:, I32])
        e[f'wv{h}'] = ('B', w[f'wv{h}'][:, I32])
        e[f'wo{h}'] = ('A', w[f'wo{h}'][:, I32])
        e[f'bias{h}'] = ('H', w[f'bias{h}'][np.ix_(inter(64), I96)].T)
    for b in range(4):
        e[f'w1_{b}'] = ('A', w[f'w1_{b}'][:, I32])
        e[f'b1_{b}'] = ('H', w[f'b1_{b}'][I32])
        e[f'w2_{b}'] = ('A', w[f'w2_{b}'][:, I32])
    e['wm'], e['bm'] = ('A', w['wm'][:, I64]), ('H', w['bm'][I64])
    e['wh'], e['bh'] = ('A', w['wh']), ('H', w['bh'])
    e['gain0'] = ('H', w['gain0'])
    for k in ('table0', 'gain1', 'table1'):
        e[k] = ('H', w[k][I32])
    e['cubic'] = ('U', cubic_table())
    e['act'] = ('Y', act_table())
    blob, defines = bytearray(), []
    for name, (kind, a) in e.items():
        while len(blob) % 256:
            blob.append(0)
        off = len(blob)
        if kind == 'A':
            blob += a_tiles(a).tobytes()
        elif kind == 'B':
            blob += b_tiles(a).tobytes()
        elif kind == 'Y':
            blob += np.ascontiguousarray(a, np.uint8).tobytes()
        elif kind == 'U':
            blob += np.ascontiguousarray(a, np.uint16).tobytes()
        else:
            blob += np.ascontiguousarray(a, np.float16).tobytes()
        defines.append(f'#define W_{name.upper()} {base + off}u   // {kind} {a.shape}')
    open(out_bin, 'wb').write(bytes(blob))
    open(out_h, 'w').write('// generated by engine/rr/enc0_pack.py\n' + '\n'.join(defines) + '\n')
    print(f'{len(blob)} bytes, {len(e)} entries, base {base}')


if __name__ == '__main__':
    main()
